export type Lang = "en" | "vi";
const dicts: Record<Lang, Record<TKey, string>> = { en, vi };

export function resolveLang(pref: "auto" | Lang): Lang {
  if (pref !== "auto") return pref;
  return navigator.language.toLowerCase().startsWith("vi") ? "vi" : "en";
}

export function currentLang(): Lang {
  return resolveLang(useApp.getState().lang);
}

export type Vars = Record<string, string | number>;

export function translate(lang: Lang, key: TKey, vars?: Vars): string {
  let s = dicts[lang][key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

/** t() outside React (notifications, toasts). */
export function t(key: TKey, vars?: Vars): string {
  return translate(currentLang(), key, vars);
}

/** Hook: re-renders the component when the language changes. */
export function useT(): (key: TKey, vars?: Vars) => string {
  const lang = resolveLang(useApp((s) => s.lang));
  return (key, vars) => translate(lang, key, vars);
}
